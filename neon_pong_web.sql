CREATE DATABASE IF NOT EXISTS neon_pong_web CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE neon_pong_web;

CREATE TABLE IF NOT EXISTS web_matches (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    player_name VARCHAR(40) NOT NULL,
    level_number TINYINT UNSIGNED NOT NULL,
    won BOOLEAN NOT NULL DEFAULT FALSE,
    score INT UNSIGNED NOT NULL DEFAULT 0,
    duration_seconds INT UNSIGNED NOT NULL DEFAULT 0,
    played_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_matches_player (player_name),
    INDEX idx_matches_played_at (played_at)
);

CREATE TABLE IF NOT EXISTS web_progress (
    player_name VARCHAR(40) NOT NULL PRIMARY KEY,
    highest_level TINYINT UNSIGNED NOT NULL DEFAULT 1,
    total_wins INT UNSIGNED NOT NULL DEFAULT 0,
    best_score INT UNSIGNED NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
